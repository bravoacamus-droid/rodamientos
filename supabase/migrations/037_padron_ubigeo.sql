-- Verificación
-- ---------------------------------------------------------------------------
do $$
declare
  v_n        int;
  v_texto    text;
  v_sunat    text;
begin
  select count(*) into v_n from ubigeo;
  if v_n <> 1874 then
    raise exception 'El padrón quedó con % distritos y deberían ser 1.874', v_n;
  end if;

  select count(distinct departamento) into v_n from ubigeo;
  if v_n <> 25 then raise exception 'Quedaron % departamentos y son 25', v_n; end if;

  select count(*) into v_n from (select distinct departamento, provincia from ubigeo) x;
  if v_n <> 196 then raise exception 'Quedaron % provincias y son 196', v_n; end if;

  -- Los 64 de la 007 conservan su nombre bien escrito. Si esto salta, el
  -- `on conflict` está pisando lo que no debe.
  select u.distrito into v_texto from ubigeo u where u.codigo = '150119';
  if v_texto <> 'Lurín' then
    raise exception 'Se pisó el nombre revisado a mano: 150119 quedó como «%»', v_texto;
  end if;
  select u.distrito into v_texto from ubigeo u where u.codigo = '150123';
  if v_texto <> 'Pachacámac' then
    raise exception 'Se pisó el nombre revisado a mano: 150123 quedó como «%»', v_texto;
  end if;

  -- La concordancia, que es lo que hace falta para la guía. Huaribamba es el
  -- caso de manual: INEI 090708, SUNAT 090709.
  select u.codigo_sunat, u.distrito into v_sunat, v_texto from ubigeo u where u.codigo = '090708';
  if v_sunat is distinct from '090709' or v_texto <> 'Huaribamba' then
    raise exception 'La concordancia de Huaribamba está mal: % / %', v_sunat, v_texto;
  end if;

  -- Putumayo: el INEI le dio provincia propia y SUNAT lo dejó en Maynas.
  select u.codigo_sunat into v_sunat from ubigeo u where u.codigo = '160801';
  if v_sunat is distinct from '160109' then
    raise exception 'La concordancia de Putumayo está mal: %', v_sunat;
  end if;

  -- Los que SUNAT no conoce quedan en null y NO en el código del INEI: es la
  -- diferencia entre negarse a emitir y emitir a otro sitio.
  select count(*) into v_n from ubigeo where codigo_sunat is null;
  if v_n <> 41 then
    raise exception 'Deberían quedar 41 distritos sin código de SUNAT y hay %', v_n;
  end if;
  if exists (select 1 from ubigeo where codigo = '090717' and codigo_sunat is not null) then
    raise exception 'Quichuas tiene código de SUNAT y SUNAT no lo conoce';
  end if;

  -- Y el caso que lo empezó todo: el cliente real de Quillabamba, Cusco, que
  -- se guardó sin distrito porque no lo teníamos.
  if not exists (
    select 1 from ubigeo
     where public.normalizar_texto(distrito) = 'santa ana'
       and public.normalizar_texto(provincia) = 'la convencion'
  ) then
    raise exception 'Falta Santa Ana / La Convención, que es el cliente de Quillabamba';
  end if;

  raise notice 'Ubigeo: 1.874 distritos, 196 provincias, 25 departamentos, con la concordancia de SUNAT.';
end $$;
